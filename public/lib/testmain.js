// The package main that `go test` would generate to drive a unit's tests:
// it lists the test functions (found by the checker) and hands them to
// testing.MainStart. Compiled against the unit's package, imported as _test.

/**
 * @typedef {Object} TestFunc
 * @property {string} name
 * @property {"test"|"benchmark"|"fuzz"|"example"} kind
 * @property {string} [output] examples only: expected output; absent = compile but don't run
 * @property {boolean} [unordered]
 */

/**
 * @param {string} pkg the unit's package (and import path)
 * @param {TestFunc[]} tests
 * @param {boolean} hasTestMain
 * @returns {string}
 */
export function testmain(pkg, tests, hasTestMain) {
  const of = (/** @type {string} */ kind) => tests.filter((t) => t.kind === kind);
  // JSON string literals are valid Go string literals.
  const q = JSON.stringify;
  const list = (/** @type {string} */ type, /** @type {string[]} */ items) =>
    `var ${type[0].toLowerCase() + type.slice(1)}s = []testing.Internal${type}{\n${items.map((i) => `\t${i},\n`).join("")}}\n`;
  return `// Code generated by pizza2go. DO NOT EDIT.

package main

import (
	"os"
${hasTestMain ? '\t"reflect"\n' : ""}	"testing"
	"testing/internal/testdeps"

	_test ${q(pkg)}
)

${list("Test", of("test").map((t) => `{${q(t.name)}, _test.${t.name}}`))}
${list("Benchmark", of("benchmark").map((t) => `{${q(t.name)}, _test.${t.name}}`))}
${list("FuzzTarget", of("fuzz").map((t) => `{${q(t.name)}, _test.${t.name}}`))}
${list(
  "Example",
  of("example")
    .filter((t) => t.output !== undefined)
    .map((t) => `{${q(t.name)}, _test.${t.name}, ${q(t.output)}, ${Boolean(t.unordered)}}`)
)}
func init() {
	testdeps.ImportPath = ${q(pkg)}
}

func main() {
	m := testing.MainStart(testdeps.TestDeps{}, tests, benchmarks, fuzzTargets, examples)
${
  hasTestMain
    ? '\t_test.TestMain(m)\n\tos.Exit(int(reflect.ValueOf(m).Elem().FieldByName("exitCode").Int()))\n'
    : "\tos.Exit(m.Run())\n"
}}
`;
}
